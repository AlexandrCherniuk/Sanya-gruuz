// Страницы популярных маршрутов (RU). Пути те же, что в UA; тексты под русские запросы
// («грузоперевозки Киев — Львов»). Ставки те же, что на сайте.
import type { ServicePage } from './types'

const fmt = (n: number) => Math.round(n / 100) * 100
const uah = (n: number) => `${fmt(n).toLocaleString('ru-RU').replace(/ /g, ' ')} грн`

type RouteInput = {
  slug: string
  /** «Львов» — для заголовков */
  to: string
  /** «Львова» — как на сайте: «Киев — Львов» в таблице */
  toTable: string
  toWhere: string
  fromWhere: string
  km: number
  via: string
  about: string
  cargo: string[]
  extraFaq: { q: string; a: string }[]
}

function routePage(r: RouteInput): ServicePage {
  const bus = uah(r.km * 20)
  return {
    slug: r.slug,
    group: 'ukraine',
    route: { from: 'Киев', to: r.toTable, km: r.km },
    meta: {
      title: `Грузоперевозки Киев — ${r.to}: цена от ${bus}`,
      description: `Перевозка грузов Киев — ${r.to} и ${r.to} — Киев: бус, 5–10 т, фура 22 т. Около ${r.km} км, отдельная машина от ${bus} или догруз. Договор, цена до загрузки.`,
    },
    card: { icon: 'route', title: `Киев — ${r.to}`, text: `~${r.km} км, в обе стороны`, price: `от ${bus}` },
    h1: `Грузоперевозки Киев — ${r.to}`,
    lead: `Перевезём груз из Киева ${r.toWhere} и обратно: отдельной машиной под ваш груз или догрузом, если груз небольшой. Цену называем до загрузки и фиксируем в договоре-заявке.`,
    bullets: [`~${r.km} км, бус от ${bus}`, 'Отдельная машина или догруз', 'В обе стороны'],
    priceFrom: `от ${bus}`,
    intro: {
      title: `Как возим Киев — ${r.to}`,
      paragraphs: [
        `Расстояние между городами по трассе — около ${r.km} км, маршрут ${r.via}. Отдельная машина выезжает сразу после загрузки и идёт без заездов к другим клиентам.`,
        r.about,
        `Если груз занимает часть кузова, предлагаем догруз: вы платите за своё место в машине, а не за весь рейс. Так же возим в обратном направлении, ${r.fromWhere} в Киев.`,
      ],
    },
    cargo: { title: 'Что возим по этому маршруту', items: r.cargo },
    sections: [
      {
        title: 'От чего зависит цена',
        items: [
          'Вес и объём груза: от них зависит, какая машина нужна',
          'Точные адреса загрузки и выгрузки в Киеве и городе доставки',
          'Отдельная машина или догруз',
          'Грузчики, гидроборт, дополнительные точки по пути',
          'Срочность и дата: перед выходными машины разбирают быстрее',
        ],
      },
      {
        title: 'Как заказать',
        text: 'Оставьте заявку или напишите в мессенджер: маршрут, что везёте, вес и примерный объём. Логист подберёт машину, назовёт цену, и после согласования подпишем договор-заявку.',
      },
    ],
    prices: {
      title: `Цены Киев — ${r.to}`,
      rows: [
        { label: 'Бус до 2 т, до 20 м³', value: `от ${bus}` },
        { label: 'Грузовик до 5 т', value: `от ${uah(r.km * 30)}` },
        { label: 'Грузовик до 10 т', value: `от ${uah(r.km * 35)}` },
        { label: 'Фура до 22 т', value: `от ${uah(r.km * 45)}` },
        { label: 'Догруз', value: 'дешевле отдельной машины', note: 'за место в кузове' },
      ],
      note: `Расчёт по минимальной ставке отдельной машины на ~${r.km} км. Точную сумму логист назовёт после заявки.`,
    },
    vehicles: ['bus', 't5', 't10', 'fura'],
    faq: [
      {
        q: `Сколько стоит перевозка Киев — ${r.to}?`,
        a: `Ориентир для отдельной машины: бус до 2 т — от ${bus}, грузовик до 5 т — от ${uah(r.km * 30)}, фура 22 т — от ${uah(r.km * 45)}. Догрузом выходит дешевле. Точную цену назовём, когда будем знать вес, объём и адреса.`,
      },
      {
        q: 'Сколько едет груз?',
        a: `Отдельная машина проходит ~${r.km} км обычно за один день в пути. Догруз идёт по графику рейса, поэтому срок логист уточнит под вашу дату.`,
      },
      {
        q: `Возите ли ${r.fromWhere} в Киев?`,
        a: 'Да, работаем в обе стороны. Цена в обратном направлении считается так же: по весу, объёму и типу машины.',
      },
      ...r.extraFaq,
    ],
  }
}

