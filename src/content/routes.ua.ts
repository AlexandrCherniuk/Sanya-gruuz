// Страницы популярных маршрутов (UA). Структура по образцу moving-expert и master-trans
// (H1 «Вантажоперевезення Київ — місто», ціна по тоннажу, приклади, FAQ), тексти свої.
// Ставки беруться ті самі, що на сайті (грн/км), ціна маршруту = км × ставка, округлено до сотні.
import type { ServicePage } from './types'

const fmt = (n: number) => Math.round(n / 100) * 100
const uah = (n: number) => `${fmt(n).toLocaleString('uk-UA').replace(/ /g, ' ')} грн`

type RouteInput = {
  slug: string
  to: string
  /** «до Львова», «в Одесу» */
  toWhere: string
  /** «зі Львова», «з Одеси» */
  fromWhere: string
  km: number
  via: string
  about: string
  cargo: string[]
  extraFaq: { q: string; a: string }[]
}

function routePage(r: RouteInput): ServicePage {
  const bus = uah(r.km * 35)
  return {
    slug: r.slug,
    group: 'ukraine',
    route: { from: 'Київ', to: r.to, km: r.km },
    meta: {
      title: `Вантажоперевезення Київ — ${r.to}: ціна від ${bus}`,
      description: `Перевезення вантажів Київ — ${r.to} і ${r.to} — Київ: бус, 5–10 т, фура 22 т. Близько ${r.km} км, окрема машина від ${bus} або догруз. Договір, ціна до завантаження.`,
    },
    card: { icon: 'route', title: `Київ — ${r.to}`, text: `~${r.km} км, в обидва боки`, price: `від ${bus}` },
    h1: `Вантажоперевезення Київ — ${r.to}`,
    lead: `Перевеземо вантаж з Києва ${r.toWhere} і назад: окремою машиною під ваш вантаж або догрузом, якщо вантаж невеликий. Ціну називаємо до завантаження і фіксуємо в договорі-заявці.`,
    bullets: [`~${r.km} км, бус від ${bus}`, 'Окрема машина або догруз', 'В обидва боки'],
    priceFrom: `від ${bus}`,
    intro: {
      title: `Як возимо Київ — ${r.to}`,
      paragraphs: [
        `Відстань між містами по трасі — близько ${r.km} км, маршрут ${r.via}. Окрема машина виїжджає одразу після завантаження і їде без заїздів до інших клієнтів.`,
        r.about,
        `Якщо вантаж займає частину кузова, пропонуємо догруз: ви платите за своє місце в машині, а не за весь рейс. Так само возимо у зворотному напрямку, ${r.fromWhere} до Києва.`,
      ],
    },
    cargo: { title: 'Що возимо цим маршрутом', items: r.cargo },
    sections: [
      {
        title: 'Від чого залежить ціна',
        items: [
          'Вага й об’єм вантажу: від них залежить, яка машина потрібна',
          'Точні адреси завантаження і розвантаження в Києві та місті доставки',
          'Окрема машина чи догруз',
          'Вантажники, гідроборт, додаткові точки по дорозі',
          'Терміновість і дата: перед вихідними машини розбирають швидше',
        ],
      },
      {
        title: 'Як замовити',
        text: 'Залиште заявку або напишіть у месенджер: маршрут, що везете, вагу й орієнтовний об’єм. Логіст підбере машину, назве ціну, і після погодження підпишемо договір-заявку.',
      },
    ],
    prices: {
      title: `Ціни Київ — ${r.to}`,
      rows: [
        { label: 'Бус до 2 т, до 20 м³', value: `від ${bus}` },
        { label: 'Вантажівка до 5 т', value: `від ${uah(r.km * 50)}` },
        { label: 'Вантажівка до 10 т', value: `від ${uah(r.km * 60)}` },
        { label: 'Фура до 22 т', value: `від ${uah(r.km * 70)}` },
        { label: 'Догруз', value: 'дешевше окремої машини', note: 'за місце в кузові' },
      ],
      note: `Розрахунок за мінімальною ставкою окремої машини на ~${r.km} км. Точну суму логіст назве після заявки.`,
    },
    vehicles: ['bus', 't5', 't10', 'fura'],
    faq: [
      {
        q: `Скільки коштує перевезення Київ — ${r.to}?`,
        a: `Орієнтир для окремої машини: бус до 2 т — від ${bus}, вантажівка до 5 т — від ${uah(r.km * 50)}, фура 22 т — від ${uah(r.km * 70)}. Догрузом виходить дешевше. Точну ціну назвемо, коли знатимемо вагу, об’єм і адреси.`,
      },
      {
        q: 'Скільки їде вантаж?',
        a: `Окрема машина проходить ~${r.km} км зазвичай за один день у дорозі. Догруз іде за графіком рейсу, тому термін логіст уточнить під вашу дату.`,
      },
      {
        q: `Чи возите ${r.fromWhere} до Києва?`,
        a: 'Так, працюємо в обидва боки. Ціна для зворотного напрямку рахується так само: від ваги, об’єму і типу машини.',
      },
      ...r.extraFaq,
    ],
  }
}

